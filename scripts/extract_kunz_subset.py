#!/usr/bin/env python
"""Extract the Kunz et al. 2025 sentenceData subset used by this project.

Reads the member list from configs/data/kunz.yaml, extracts ONLY those members
(flat, by basename) from the Dryad archive ``sentenceData.zip`` into the output
directory, verifies CRC-32 of every member, computes SHA-256 of each extracted
file and of the source archive, and writes data/MANIFEST.md.

The source archive is opened read-only and never modified. Its location is a
required argument so that no machine-specific path is stored in the repo.

Usage:
    python -I scripts/extract_kunz_subset.py --zip /path/to/sentenceData.zip
        [--out data/raw/kunz/sentenceData] [--config configs/data/kunz.yaml]

Dependencies: Python stdlib + PyYAML (+ numpy, through wvx.seeding).
"""

from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import os
import sys
import tempfile
import zipfile
import zlib
from pathlib import Path, PurePosixPath

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from wvx.config import load_config  # noqa: E402
from wvx.seeding import set_seed  # noqa: E402

DEFAULT_CONFIG = REPO_ROOT / "configs" / "data" / "kunz.yaml"
CHUNK = 8 * 1024 * 1024


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def safe_basename(member_name: str) -> str:
    """Return a safe flat file name for a zip member, or raise ValueError.

    Rejects absolute paths, '..' components, backslashes, macOS resource-fork
    entries (__MACOSX/), .DS_Store, directory entries and empty names.
    """
    if "\\" in member_name or "\x00" in member_name:
        raise ValueError(f"illegal characters in member name: {member_name!r}")
    p = PurePosixPath(member_name)
    if p.is_absolute() or any(part == ".." for part in p.parts):
        raise ValueError(f"unsafe member path: {member_name!r}")
    if member_name.endswith("/"):
        raise ValueError(f"member is a directory: {member_name!r}")
    if p.parts and p.parts[0] == "__MACOSX":
        raise ValueError(f"refusing __MACOSX member: {member_name!r}")
    name = p.name
    if not name or name in (".", "..") or name == ".DS_Store" or name.startswith("._"):
        raise ValueError(f"refusing member: {member_name!r}")
    return name


def is_symlink_member(info: zipfile.ZipInfo) -> bool:
    # Unix mode lives in the high 16 bits of external_attr (when created on Unix).
    mode = (info.external_attr >> 16) & 0o170000
    return mode == 0o120000


def stream_member(zf: zipfile.ZipFile, info: zipfile.ZipInfo, dest_fh=None) -> tuple[str, int, int]:
    """Stream a member, returning (sha256, crc32, n_bytes). Optionally write to dest_fh."""
    h = hashlib.sha256()
    crc = 0
    n = 0
    with zf.open(info, "r") as src:  # zipfile itself also raises BadZipFile on CRC mismatch
        for chunk in iter(lambda: src.read(CHUNK), b""):
            h.update(chunk)
            crc = zlib.crc32(chunk, crc)
            n += len(chunk)
            if dest_fh is not None:
                dest_fh.write(chunk)
    return h.hexdigest(), crc & 0xFFFFFFFF, n


def rel_to_repo(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return "<output directory outside repository>"


def human_bytes(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1000 or unit == "TB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.2f} {unit}"
        n /= 1000.0
    return f"{n}"


def write_manifest(manifest_path: Path, cfg: dict, archive_name: str, archive_size: int,
                   archive_sha: str, out_dir: Path, rows: list[dict]) -> None:
    ds = cfg.get("dataset", {})
    today = _dt.date.today().isoformat()
    lines = [
        "# Data manifest",
        "",
        "Generated by `scripts/extract_kunz_subset.py`. Do not edit by hand; re-run the script.",
        "",
        "## Kunz et al. 2025 -- sentenceData subset",
        "",
        f"- **Dataset:** {ds.get('name', 'UNKNOWN')}",
        f"- **Citation:** {' '.join(str(ds.get('citation', 'UNKNOWN')).split())}",
        f"- **DOI:** [{ds.get('doi', 'UNKNOWN')}]({ds.get('url', '')})",
        f"- **Source archive:** `{archive_name}`",
        f"- **Archive size:** {archive_size} bytes ({human_bytes(archive_size)})",
        f"- **Archive SHA-256:** `{archive_sha}`",
        f"- **Extraction date:** {today}",
        f"- **Output directory (repo-relative):** `{rel_to_repo(out_dir)}/`",
        "- CRC-32 of every extracted member was verified against the archive's central directory.",
        "",
        "| File | Bytes | SHA-256 | Archive member |",
        "|---|---:|---|---|",
    ]
    for r in rows:
        lines.append(f"| `{r['file']}` | {r['bytes']} | `{r['sha256']}` | `{r['member']}` |")
    lines.append("")
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--zip", required=True, type=Path, help="path to sentenceData.zip (opened read-only)")
    ap.add_argument("--config", type=Path, default=DEFAULT_CONFIG, help="dataset config YAML")
    ap.add_argument("--out", type=Path, default=None,
                    help="output directory (default: output_dir from config, relative to repo root)")
    ap.add_argument("--manifest", type=Path, default=None,
                    help="manifest path (default: manifest from config, relative to repo root)")
    args = ap.parse_args(argv)
    set_seed(int(load_config()["seed"]))  # nothing here is random; AGENTS.md rule 7

    with open(args.config, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)

    members: list[str] = list(cfg["members"])
    expected_archive = cfg.get("archive", {}).get("name")
    out_dir = args.out if args.out is not None else REPO_ROOT / cfg["output_dir"]
    manifest_path = args.manifest if args.manifest is not None else REPO_ROOT / cfg.get("manifest", "data/MANIFEST.md")
    out_dir = out_dir.resolve()
    zip_path = args.zip.resolve()

    if not zip_path.is_file():
        print(f"ERROR: archive not found: {args.zip}", file=sys.stderr)
        return 2
    if expected_archive and zip_path.name != expected_archive:
        print(f"WARNING: archive file name {zip_path.name!r} != expected {expected_archive!r}", file=sys.stderr)
    if out_dir == zip_path.parent or zip_path.parent in out_dir.parents:
        print("ERROR: refusing to extract into (or below) the source archive's folder", file=sys.stderr)
        return 2

    # Validate names up front (and detect basename collisions).
    flat_names = {}
    for m in members:
        name = safe_basename(m)
        if name in flat_names.values():
            raise ValueError(f"basename collision for {m!r}")
        flat_names[m] = name

    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    with zipfile.ZipFile(zip_path, "r") as zf:
        infos = {i.filename: i for i in zf.infolist()}
        for m in members:
            if m not in infos:
                print(f"ERROR: member not in archive: {m}", file=sys.stderr)
                return 3
            info = infos[m]
            if info.is_dir() or is_symlink_member(info):
                print(f"ERROR: member is a directory or symlink: {m}", file=sys.stderr)
                return 3
            name = flat_names[m]
            target = (out_dir / name).resolve()
            if target.parent != out_dir:  # zip-slip guard (belt and braces)
                print(f"ERROR: unsafe target path for {m}", file=sys.stderr)
                return 3

            if target.is_file() and target.stat().st_size == info.file_size:
                print(f"[check] {name}: exists, verifying against archive ...", flush=True)
                existing_sha = sha256_file(target)
                member_sha, crc, n = stream_member(zf, info)
                if crc != info.CRC or n != info.file_size:
                    print(f"ERROR: CRC/size mismatch reading {m} from archive", file=sys.stderr)
                    return 4
                if existing_sha == member_sha:
                    print(f"[skip]  {name}: SHA-256 matches archive member", flush=True)
                    rows.append({"file": name, "bytes": n, "sha256": existing_sha, "member": m})
                    continue
                print(f"[redo]  {name}: SHA-256 differs from archive member; re-extracting", flush=True)

            print(f"[extract] {m} -> {name} ({info.file_size} bytes)", flush=True)
            fd, tmp = tempfile.mkstemp(prefix=f".{name}.", suffix=".part", dir=out_dir)
            try:
                with os.fdopen(fd, "wb") as fh:
                    member_sha, crc, n = stream_member(zf, info, fh)
                if crc != info.CRC:
                    raise IOError(f"CRC mismatch for {m}: got {crc:08x}, expected {info.CRC:08x}")
                if n != info.file_size:
                    raise IOError(f"size mismatch for {m}: got {n}, expected {info.file_size}")
                # mkstemp creates 0600 files; give the result normal permissions (respecting umask).
                umask = os.umask(0)
                os.umask(umask)
                os.chmod(tmp, 0o666 & ~umask)
                os.replace(tmp, target)
            except BaseException:
                if os.path.exists(tmp):
                    os.unlink(tmp)
                raise
            disk_sha = sha256_file(target)
            if disk_sha != member_sha:
                print(f"ERROR: on-disk SHA-256 differs from streamed SHA-256 for {name}", file=sys.stderr)
                return 4
            rows.append({"file": name, "bytes": n, "sha256": disk_sha, "member": m})
            print(f"[ok]    {name}: CRC {crc:08x} verified, SHA-256 {disk_sha}", flush=True)

    print("[hash] computing SHA-256 of source archive ...", flush=True)
    archive_size = zip_path.stat().st_size
    archive_sha = sha256_file(zip_path)
    print(f"[hash] {zip_path.name}: {archive_size} bytes, SHA-256 {archive_sha}", flush=True)
    expected_sha = cfg.get("archive", {}).get("sha256")
    if expected_sha and archive_sha != expected_sha:
        print(f"ERROR: archive SHA-256 differs from the Dryad-published digest {expected_sha}",
              file=sys.stderr)
        return 1
    if expected_sha:
        print("[hash] archive SHA-256 matches the Dryad-published digest", flush=True)

    write_manifest(manifest_path, cfg, zip_path.name, archive_size, archive_sha, out_dir, rows)
    print(f"[manifest] wrote {rel_to_repo(manifest_path)}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
